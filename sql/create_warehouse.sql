CREATE TABLE dim_customer (
    customer_key   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    VARCHAR2(20) NOT NULL,
    customer_name  VARCHAR2(200),
    segment        VARCHAR2(30),
    updated_at     TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT uq_dim_customer_bk UNIQUE (customer_id)
);

CREATE TABLE dim_product (
    product_key    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     VARCHAR2(30) NOT NULL,
    product_name   VARCHAR2(255),
    category       VARCHAR2(50),
    sub_category   VARCHAR2(50),
    updated_at     TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT uq_dim_product_bk UNIQUE (product_id)
);

CREATE TABLE dim_geography (
    geography_key  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country        VARCHAR2(100) NOT NULL,
    state          VARCHAR2(100) NOT NULL,
    city           VARCHAR2(100) NOT NULL,
    postal_code    VARCHAR2(10)  NOT NULL,
    region         VARCHAR2(30),
    CONSTRAINT uq_dim_geo_bk UNIQUE (country, state, city, postal_code)
);

CREATE TABLE dim_date (
    date_key      NUMBER(8) PRIMARY KEY,
    full_date     DATE NOT NULL,
    day_num       NUMBER(2),
    month_num     NUMBER(2),
    month_name    VARCHAR2(15),
    quarter_num   NUMBER(1),
    year_num      NUMBER(4),
    week_of_year  NUMBER(2),
    day_of_week   NUMBER(1),
    day_name      VARCHAR2(15),
    is_weekend    NUMBER(1) DEFAULT 0 CHECK (is_weekend IN (0,1)),
    CONSTRAINT uq_dim_date_full UNIQUE (full_date)
);

CREATE TABLE fact_sales (
    sales_key       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    row_id          NUMBER       NOT NULL,
    order_id        VARCHAR2(30) NOT NULL,
    customer_key    NUMBER NOT NULL,
    product_key     NUMBER NOT NULL,
    geography_key   NUMBER NOT NULL,
    order_date_key  NUMBER(8) NOT NULL,
    ship_date_key   NUMBER(8) NOT NULL,
    ship_mode       VARCHAR2(30),
    sales_amount    NUMBER(14,4) NOT NULL CHECK (sales_amount >= 0),
    quantity        NUMBER(8),
    discount_rate   NUMBER(5,4) CHECK (discount_rate BETWEEN 0 AND 1),
    profit          NUMBER(14,4),
    shipping_days   NUMBER(4),
    loaded_at       TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT uq_fact_row_id UNIQUE (row_id),
    CONSTRAINT fk_fact_customer  FOREIGN KEY (customer_key)   REFERENCES dim_customer(customer_key),
    CONSTRAINT fk_fact_product   FOREIGN KEY (product_key)    REFERENCES dim_product(product_key),
    CONSTRAINT fk_fact_geo       FOREIGN KEY (geography_key)  REFERENCES dim_geography(geography_key),
    CONSTRAINT fk_fact_odate     FOREIGN KEY (order_date_key) REFERENCES dim_date(date_key),
    CONSTRAINT fk_fact_sdate     FOREIGN KEY (ship_date_key)  REFERENCES dim_date(date_key)
);